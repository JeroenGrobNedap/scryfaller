// Downloads Scryfall's keyword and subtype catalogs into src/app/query/keywords.ts.
// Run with `npm run update-keywords` after a new set adds keywords.
import { writeFile } from 'node:fs/promises';

const get = async (name) => {
  const res = await fetch(`https://api.scryfall.com/catalog/${name}`, {
    headers: { 'User-Agent': 'Scryfaller/1.0', Accept: 'application/json' },
  });
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status}`);
  await new Promise((r) => setTimeout(r, 150));
  return (await res.json()).data;
};
const sorted = (lists) => [...new Set(lists.flat())].sort((a, b) => a.localeCompare(b));

const keywords = sorted([await get('keyword-abilities'), await get('keyword-actions'), await get('ability-words')]);
const subtypes = sorted([
  await get('creature-types'),
  await get('artifact-types'),
  await get('enchantment-types'),
  await get('land-types'),
  await get('spell-types'),
]);
const list = (items) => items.map((s) => `  ${JSON.stringify(s)},`).join('\n');

await writeFile(
  new URL('../src/app/query/keywords.ts', import.meta.url),
  `// Generated by scripts/update-keywords.mjs from Scryfall's catalogs. Do not edit by hand.

/** Keyword abilities, keyword actions and ability words. */
export const KEYWORDS: string[] = [
${list(keywords)}
];

/** Creature, artifact, enchantment, land and spell types. */
export const SUBTYPES: string[] = [
${list(subtypes)}
];
`,
);
console.log(`${keywords.length} keywords, ${subtypes.length} subtypes`);
